package egress

import (
	"fmt"
	"net"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Proxychains closes the last outbound gap: tools that open raw sockets and
// ignore the HTTP_PROXY/ALL_PROXY environment variables (nmap's connect paths,
// sqlmap, hydra, and most CLI scanners) will not route through the gateway on
// env injection alone. Wrapping their process with proxychains forces every
// TCP connect() through the configured proxy via LD_PRELOAD.
//
// IMPORTANT LIMITS (proxychains cannot tunnel what the kernel sends raw):
//   - It hooks connect() for TCP only. UDP and ICMP are NOT tunneled.
//   - nmap SYN scan (-sS), ping host-discovery (default), and OS detection use
//     raw packets that bypass proxychains and WILL leak the real IP. To stay
//     anonymous, nmap must run as a TCP connect scan with no ping and remote
//     DNS: `nmap -sT -Pn -n` (or supply targets by IP). This is a usage
//     constraint, not something the wrapper can enforce on arbitrary argv.
//   - For a hard guarantee regardless of tool behavior, pair this with an
//     OS-level kill-switch (firewall rule dropping all non-proxy egress).
//     See docs/en-US/egress-privacy.md.

// proxychainsBinaries are the candidate executable names, newest first.
var proxychainsBinaries = []string{"proxychains4", "proxychains"}

// tempDirName is the single directory under the OS temp root that the gateway
// writes its generated artifacts (proxychains.conf) into, so cleanup has one
// well-known place to remove.
const tempDirName = "cyberstrike-egress"

// TempDir returns the directory where the gateway writes temporary artifacts.
func TempDir() string {
	return filepath.Join(os.TempDir(), tempDirName)
}

// CleanupTempFiles removes every temporary artifact the egress gateway wrote
// (notably proxychains.conf, which can contain proxy credentials). It is safe
// to call when nothing was written and should be called on shutdown so the
// platform does not leave junk — or credentials — behind after a test.
func CleanupTempFiles() error {
	dir := TempDir()
	// Confine deletion to our own temp subdirectory, never os.TempDir() itself.
	if filepath.Base(dir) != tempDirName {
		return fmt.Errorf("egress: refusing to clean unexpected temp dir %q", dir)
	}
	err := os.RemoveAll(dir)
	if err == nil || os.IsNotExist(err) {
		return nil
	}
	return err
}

// ProxychainsBinary returns the path to a proxychains executable, or "" when
// none is installed.
func ProxychainsBinary() string {
	for _, name := range proxychainsBinaries {
		if p, err := exec.LookPath(name); err == nil {
			return p
		}
	}
	return ""
}

// ProxychainsSupported reports whether spawned tools should be wrapped: the
// gateway is enabled, its mode is a chainable proxy, wrapping is not turned
// off, and a proxychains binary is available.
func (g *Gateway) ProxychainsSupported() bool {
	if g == nil || !g.Enabled() {
		return false
	}
	if strings.EqualFold(strings.TrimSpace(g.cfg.ProxychainsMode), "off") {
		return false
	}
	switch g.mode {
	case ModeSOCKS5, ModeTor, ModeHTTP, ModeHTTPS:
	default:
		return false
	}
	return ProxychainsBinary() != ""
}

// proxychainsConfContent builds a proxychains configuration from the gateway's
// proxy settings.
func (g *Gateway) proxychainsConfContent() (string, error) {
	host, port, err := net.SplitHostPort(g.addr)
	if err != nil {
		return "", fmt.Errorf("egress: parse proxy address %q: %w", g.addr, err)
	}

	var proxyType string
	switch g.mode {
	case ModeSOCKS5, ModeTor:
		proxyType = "socks5"
	case ModeHTTP, ModeHTTPS:
		// proxychains speaks plain HTTP CONNECT; an HTTPS proxy hop is not
		// distinguished here.
		proxyType = "http"
	default:
		return "", fmt.Errorf("egress: mode %q is not proxychains-compatible", g.mode)
	}

	var b strings.Builder
	b.WriteString("# Generated by CyberStrikeAI egress gateway. Do not edit by hand.\n")
	b.WriteString("strict_chain\n")
	if g.cfg.DNSThroughProxy {
		b.WriteString("proxy_dns\n")
	}
	b.WriteString("tcp_read_time_out 15000\n")
	b.WriteString("tcp_connect_time_out 8000\n")
	b.WriteString("[ProxyList]\n")

	line := fmt.Sprintf("%s %s %s", proxyType, host, port)
	if g.cfg.Username != "" || g.cfg.Password != "" {
		line += fmt.Sprintf(" %s %s", g.cfg.Username, g.cfg.Password)
	}
	b.WriteString(line + "\n")
	return b.String(), nil
}

// ProxychainsConfPath writes the generated proxychains config to a temp file
// once and returns its path on every call. The file is created with 0600
// permissions because it can contain proxy credentials.
func (g *Gateway) ProxychainsConfPath() (string, error) {
	g.pcOnce.Do(func() {
		content, err := g.proxychainsConfContent()
		if err != nil {
			g.pcErr = err
			return
		}
		dir := filepath.Join(os.TempDir(), "cyberstrike-egress")
		if mkErr := os.MkdirAll(dir, 0700); mkErr != nil {
			g.pcErr = fmt.Errorf("egress: create proxychains dir: %w", mkErr)
			return
		}
		path := filepath.Join(dir, "proxychains.conf")
		if wErr := os.WriteFile(path, []byte(content), 0600); wErr != nil {
			g.pcErr = fmt.Errorf("egress: write proxychains conf: %w", wErr)
			return
		}
		g.pcPath = path
	})
	return g.pcPath, g.pcErr
}

// WrapToolCommand returns the command name and argv to actually spawn for an
// external tool. When proxychains wrapping is active it returns the
// proxychains invocation; otherwise it returns the original command unchanged.
// It never fails the caller: if the config cannot be written, it falls back to
// the unwrapped command (env-var proxying from ProxyEnv still applies).
func (g *Gateway) WrapToolCommand(name string, args []string) (string, []string) {
	if !g.ProxychainsSupported() {
		return name, args
	}
	conf, err := g.ProxychainsConfPath()
	bin := ProxychainsBinary()
	if err != nil || conf == "" || bin == "" {
		return name, args
	}
	wrapped := append([]string{"-q", "-f", conf, name}, args...)
	return bin, wrapped
}
